-- ---------------------------------------------------------------------
-- Бестиарий: свои метки ГМа, чтобы искать по ним
-- ---------------------------------------------------------------------
-- Картотека растёт, и подкласса из четырёх пунктов для поиска мало: ГМ
-- хочет свои метки («нежить», «квест-3», «Барон»), сколько угодно на запись,
-- и искать по ним. Массив текста, а не отдельная таблица: метки — это
-- свойство записи, их никто не нумерует и не переименовывает разом, а
-- «дай все записи с меткой X» по массиву в кампании из сотни строк мгновенен.
-- Права те же, что у остальных полей: пишет ГМ (bestiary_update), читает
-- тот, кому запись показана (bestiary_read).
alter table bestiary_entry add column if not exists tags text[] not null default '{}';

-- Метки правит человек руками: предел нужен не ради базы, а чтобы карточка
-- не превратилась в облако из полусотни слов.
do $do$ begin
  alter table bestiary_entry
    add constraint bestiary_entry_tags_check
    check (cardinality(tags) <= 20);
exception when duplicate_object then null;
end $do$;
